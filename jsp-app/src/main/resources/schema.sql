CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL,
 email VARCHAR(180) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('admin','librarian','member')),
 phone VARCHAR(30) NOT NULL DEFAULT '',
 address VARCHAR(500) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL UNIQUE,
 description VARCHAR(1000) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS authors (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL UNIQUE,
 country VARCHAR(100) NOT NULL,
 biography VARCHAR(1000) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS publishers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL UNIQUE,
 city VARCHAR(100) NOT NULL,
 email VARCHAR(180) NOT NULL
);
CREATE TABLE IF NOT EXISTS books (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(200) NOT NULL,
 isbn VARCHAR(30) NOT NULL UNIQUE,
 category_id BIGINT NOT NULL REFERENCES categories(id),
 author_id BIGINT NOT NULL REFERENCES authors(id),
 publisher_id BIGINT NOT NULL REFERENCES publishers(id),
 published_year INTEGER NOT NULL CHECK (published_year BETWEEN 1000 AND 2100),
 stock INTEGER NOT NULL CHECK (stock >= 0),
 shelf VARCHAR(40) NOT NULL,
 description VARCHAR(2000) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS reservations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id BIGINT NOT NULL REFERENCES users(id),
 book_id BIGINT NOT NULL REFERENCES books(id),
 reserved_on DATE NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('pending','ready','picked_up','cancelled')),
 notes VARCHAR(1000) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS loans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id BIGINT NOT NULL REFERENCES users(id),
 book_id BIGINT NOT NULL REFERENCES books(id),
 reservation_id BIGINT UNIQUE REFERENCES reservations(id),
 borrowed_on DATE NOT NULL,
 due_on DATE NOT NULL,
 returned_on DATE,
 notes VARCHAR(1000) NOT NULL DEFAULT '',
 CHECK (due_on >= borrowed_on),
 CHECK (returned_on IS NULL OR returned_on >= borrowed_on)
);
CREATE INDEX IF NOT EXISTS idx_books_category ON books(category_id);
CREATE INDEX IF NOT EXISTS idx_loans_book ON loans(book_id, returned_on);
CREATE INDEX IF NOT EXISTS idx_loans_member ON loans(member_id);
CREATE INDEX IF NOT EXISTS idx_reservations_book ON reservations(book_id, status);
CREATE INDEX IF NOT EXISTS idx_reservations_member ON reservations(member_id);
